/*
  Write a program that takes as input two numbers and print the sum.

  Output:
  Insert the first number: 1
  Insert the second number: 2
  Sum: 3
*/

#include <iostream>
using namespace std;

int main() {
	int n1;
	int n2;
	
	cin >> n1 >> n2;
	int sum = n1 + n2;
	cout << endl << sum << endl;
	return 0;
}
